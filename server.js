async function readJsonDB(filePath) {
    try {
        if (!fs.existsSync(DATA_DIR)) await fs.promises.mkdir(DATA_DIR, { recursive: true });
        if (!fs.existsSync(filePath)) return {};
        const raw = await fs.promises.readFile(filePath, 'utf8');
        return raw ? JSON.parse(raw) : {};
    } catch (err) {
        console.error(`Error reading ${filePath}:`, err);
        return {};
    }
}

// תור כתיבה לכל קובץ: שתי בקשות במקביל (למשל סיכום שיעור וצ'אט) קראו-שינו-כתבו
// את אותו קובץ, והאחרונה דרסה את הראשונה. עכשיו הפעולות רצות בזו אחר זו, וכתיבה
// נעשית לקובץ זמני ואז rename כדי שקובץ חצי-כתוב לא יפגום את בסיס הנתונים.
const dbQueues = new Map();
function enqueueDb(filePath, task) {
    const prev = dbQueues.get(filePath) || Promise.resolve();
    const next = prev.then(task, task);
    dbQueues.set(filePath, next.catch(() => {}));
    return next;
}

async function writeJsonDB(filePath, db) {
    try {
        if (!fs.existsSync(DATA_DIR)) await fs.promises.mkdir(DATA_DIR, { recursive: true });
        const tmp = filePath + '.tmp';
        await fs.promises.writeFile(tmp, JSON.stringify(db, null, 2), 'utf8');
        await fs.promises.rename(tmp, filePath);
    } catch (err) {
        console.error(`Error writing ${filePath}:`, err);
    }
}

