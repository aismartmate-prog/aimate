// מקבל "ד", "ד'", "כיתה ד׳", "4", "כיתה יא" וכד' ומחזיר מספר 1-12 (או null)
function gradeToNumber(raw) {
    if (!raw) return null;
    const s = String(raw).replace(/כיתה/g, '').replace(/[\s'"׳״`]/g, '');
    if (/^\d{1,2}$/.test(s)) {
        const n = parseInt(s, 10);
        return n >= 1 && n <= 12 ? n : null;
    }
    return HEBREW_GRADE_LETTERS[s] || null;
}

