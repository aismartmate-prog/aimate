const MALE_NAME_EXCEPTIONS = new Set(['משה','יהודה','אליהו','זכריה','ישעיהו','נתנאל','אוריה','אבשלום','גדליה','חזקיה','צדקיה','עזריה','חנניה','שמעיה','ידידיה']);

// שמות יוניסקס: קודם הופיעו ברשימת הנקבה, ולכן תלמיד בשם יובל/נועם/אור/רוני
// קיבל 'f' והמורה פנה אליו כל השיעור בלשון נקבה - אחת מ"הפדיחות" הקלאסיות.
// עדיף להחזיר null (יוני ישאל בטבעיות פעם אחת) מאשר לנחש לא נכון.
const UNISEX_FIRST_NAMES = new Set(['רוני','שי','גל','ליאור','חן','רותם','טל','עדי','אמית','סתיו','יובל','נועם','אור','עדן','שיר','נגה','גפן','אריאל']);

function guessGenderFromName(rawName) {
    if (!rawName) return null;
    const first = String(rawName).trim().split(/\s+/)[0];
    if (!first) return null;
    if (MALE_NAME_EXCEPTIONS.has(first)) return 'm';
    if (UNISEX_FIRST_NAMES.has(first)) return null;
    if (FEMALE_FIRST_NAMES.has(first)) return 'f';
    if (MALE_FIRST_NAMES.has(first)) return 'm';
    if (/(ה|ית)$/.test(first)) return 'f';
    return null; 
}

// שיעור נחשב "משמעותי" רק אם יש לו נושא ספציפי וסיכום של ממש. בלי זה, שיעורים
// ישנים עם נושא כללי/ריק (למשל "כללי") הוזרקו לזיכרון והמורה אמר לתלמיד
// "בפעם הקודמת עבדנו על כללי" ודיבר בקול רם על זה שהזיכרון לא ברור.
// ערכים לא תקינים (למשל "Unknown" שנשמר בפרופיל מהלקוח/מהמודל) נחשבים "לא ידוע"
// ולעולם לא מוצגים לתלמיד או מוזרקים להנחיה.
const GRADE_LETTERS_BY_NUM = ['', 'א', 'ב', 'ג', 'ד', 'ה', 'ו', 'ז', 'ח', 'ט', 'י', 'יא', 'יב'];
function gradeLabel(raw) {            // "ה'" / "יא'" או '' אם לא תקין
    const n = gradeToNumber(raw);
    return n ? GRADE_LETTERS_BY_NUM[n] + "'" : '';
}
function cleanGender(g) {
    const v = String(g || '').trim().toLowerCase();
    return (v === 'm' || v === 'f') ? v : null;
}
function cleanLevelPace(v) {
    const t = String(v || '').trim();
    return (!t || /^(unknown|none|null|undefined|לא ידוע)$/i.test(t)) ? '' : t;
}

const GENERIC_SUBJECTS = new Set(['', 'כללי', 'לא ידוע', 'לא הוגדר', 'general', 'unknown', 'none']);
function isMeaningfulLesson(l) {
    if (!l) return false;
    const subj = String(l.subject || '').trim().toLowerCase();
    const sum = String(l.summary || '').trim();
    if (GENERIC_SUBJECTS.has(subj) || subj.length < 2) return false;
    if (sum.length < 8 || /לא הוגדר|לא ברור|לא נלמד/.test(sum)) return false;
    return true;
}
function getMeaningfulLessons(profile) {
    return (profile && Array.isArray(profile.lessons)) ? profile.lessons.filter(isMeaningfulLesson) : [];
}

function deriveWeakPoint(profile) {
    if (!profile || !Array.isArray(profile.lessons)) return null;
    const entry = profile.lessons.filter(isMeaningfulLesson).reverse().find(l => l.difficulties && l.difficulties.trim());
    if (!entry) return null;
    if (entry.subject && entry.subject.trim()) return entry.subject.trim().slice(0, 40);
    return entry.difficulties.trim().slice(0, 50);
}

function ensureStudentProfileBasics(studentId, name) {
    if (!studentId) return Promise.resolve(null);
    return enqueueDb(STUDENTS_DB_PATH, () => ensureStudentProfileBasicsImpl(studentId, name));
}

async function ensureStudentProfileBasicsImpl(studentId, name) {
    const db = await readStudentsDB();
    let changed = false;
    if (!db[studentId]) { db[studentId] = { name: '', grade: '', gender: null, lessons: [] }; changed = true; }
    if (name && db[studentId].name !== name) { db[studentId].name = name; changed = true; }
    // ניקוי ערכים ישנים/פגומים שנשמרו בעבר (למשל כיתה "Unknown", מגדר "U")
    if (db[studentId].grade && !gradeToNumber(db[studentId].grade)) { db[studentId].grade = ''; changed = true; }
    if (db[studentId].gender && !cleanGender(db[studentId].gender)) { db[studentId].gender = null; changed = true; }
    if (db[studentId].level && !cleanLevelPace(db[studentId].level)) { db[studentId].level = ''; changed = true; }
    if (db[studentId].pace && !cleanLevelPace(db[studentId].pace)) { db[studentId].pace = ''; changed = true; }
    if (!db[studentId].gender) {
        const guessed = guessGenderFromName(name || db[studentId].name);
        if (guessed) { db[studentId].gender = guessed; changed = true; }
    }
    // כותבים לדיסק רק אם משהו באמת השתנה - ברוב הפעמים (תלמיד חוזר, כבר יש לו
    // פרופיל מלא) אין שום דבר חדש לשמור, אז אין סיבה לשלם על כתיבה מיותרת
    // בדיוק ברגע הכי רגיש למהירות - תחילת כל שיחה.
    if (changed) await writeStudentsDB(db);
    return db[studentId];
}

function buildOpeningLine(name, gender, knownGrade, teacherName, teacherGender, lastLesson) {
    const tName = teacherName || 'יוני';
    const tRole = teacherGender === 'f' ? 'המורה הפרטית שלך' : 'המורה הפרטי שלך';
    // כשאין עדיין שם - תמיד מוחזר משפט פתיחה תקין (כדי שהמורה תמיד יפתח בעצמו)
    if (!name) {
        return `שלום, אני ${tName}, ${tRole}. איך קוראים לך?`;
    }
    const intro = `שלום ${name}, אני ${tName}, ${tRole}.`;
    gender = cleanGender(gender);
    if (!gender) return `${intro} כדי שאדע איך לפנות אליך - את תלמידה או אתה תלמיד?`;
    const gLabel = gradeLabel(knownGrade);
    if (!gLabel) return `${intro} באיזו כיתה ${gender === 'f' ? 'את לומדת' : 'אתה לומד'}?`;
    const f = gender === 'f';
    // לא מציינים כיתה ולא דוחפים המשך שיעור קודם: המורה שואל במה התלמיד צריך עזרה היום
    return `${intro} במה ${f ? 'את צריכה' : 'אתה צריך'} עזרה היום - שיעורי בית, הכנה למבחן, ללמוד נושא חדש, או לחזק משהו ספציפי?`;
}

