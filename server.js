app.post('/live-tutor/api/speak', async (req, res) => {
    res.set('Access-Control-Allow-Origin', process.env.SPEAK_ALLOW_ORIGIN || '*');

    if (!API_KEY) return res.status(500).json({ error: 'GEMINI_API_KEY missing' });

    try {
        let text = (req.body && req.body.text ? String(req.body.text) : '').trim();
        if (!text) return res.status(400).json({ error: 'Missing text' });
        if (text.length > TTS_MAX_CHARS) text = text.slice(0, TTS_MAX_CHARS);

        const voice = (req.body && req.body.voice) || YONI_VOICE_NAME;
        const key = ttsKey(text, voice);

        // 1. מטמון בזיכרון
        if (ttsMemCache.has(key)) {
            const hit = ttsMemCache.get(key);
            rememberTts(key, hit);
            return res.json({ audio: hit, model: ttsModelInUse, cached: 'memory' });
        }

        // 2. מטמון בדיסק — שורד הפעלה מחדש של השרת
        // כל פעולות הדיסק כאן הפכו לא-סינכרוניות. הגרסה הקודמת השתמשה ב-
        // readFileSync על קובץ WAV שלם ואז המירה ל-base64 - שתי פעולות כבדות
        // שחוסמות את *כל* ה-event loop. כלומר בזמן שתלמיד אחד לוחץ "הקרא",
        // כל התלמידים האחרים בשיחה חיה קופאים לרגע. זה בדיוק המקור לתחושת
        // "לוקח לו מלא זמן להגיב" כשיש יותר ממשתמש אחד.
        const diskPath = path.join(TTS_CACHE_DIR, key + '.wav');
        try {
            const buf = cleanWavBuffer(await fs.promises.readFile(diskPath));
            const uri = 'data:audio/wav;base64,' + buf.toString('base64');
            rememberTts(key, uri);
            return res.json({ audio: uri, model: ttsModelInUse, cached: 'disk' });
        } catch (e) { /* לא במטמון - ממשיכים לסינתזה */ }

        // 3. סינתזה
        const { wav, model } = await synthesize(text, voice);
        const uri = 'data:audio/wav;base64,' + wav.toString('base64');

        rememberTts(key, uri);
        // כתיבה לדיסק ברקע - אין סיבה שהתלמיד יחכה לה, האודיו כבר מוכן.
        fs.promises.mkdir(TTS_CACHE_DIR, { recursive: true })
            .then(() => fs.promises.writeFile(diskPath, wav))
            .catch(() => { /* מטמון דיסק הוא בונוס */ });

        res.json({ audio: uri, model, cached: false });
    } catch (err) {
        console.error('[speak] שגיאה:', err);
        res.status(500).json({ error: err.message || String(err), attempts: err.attempts || undefined });
    }
});

