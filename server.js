const ttsDeadUntil = new Map();            // מודל שהחזיר NOT_FOUND — לא מנסים אותו שוב חצי שעה
async function discoverTtsModels() {
    if (ttsDiscovered.length && Date.now() - ttsDiscoveredAt < 6 * 3600 * 1000) return ttsDiscovered;
    const found = [];
    try {
        let url = 'https://generativelanguage.googleapis.com/v1beta/models?pageSize=200&key=' + encodeURIComponent(API_KEY);
        for (let i = 0; i < 4 && url; i++) {
            const r = await fetch(url);
            if (!r.ok) throw new Error('list models ' + r.status);
            const j = await r.json();
            (j.models || []).forEach(m => {
                const n = String(m.name || '').replace(/^models\//, '');
                const ok = !m.supportedGenerationMethods || m.supportedGenerationMethods.indexOf('generateContent') > -1;
                if (/tts/i.test(n) && ok) found.push(n);
            });
            url = j.nextPageToken ? 'https://generativelanguage.googleapis.com/v1beta/models?pageSize=200&pageToken=' + encodeURIComponent(j.nextPageToken) + '&key=' + encodeURIComponent(API_KEY) : null;
        }
        // מעדיפים flash (מהיר וזול) לפני pro
        found.sort((a, b) => (/flash/i.test(b) ? 1 : 0) - (/flash/i.test(a) ? 1 : 0));
        if (found.length) console.log('[speak] מודלי TTS זמינים:', found.join(', '));
    } catch (e) { console.warn('[speak] גילוי מודלים נכשל:', e.message); }
    ttsDiscovered = found; ttsDiscoveredAt = Date.now();
    return found;
}
let ttsModelInUse = null;               // ננעל אחרי ההצלחה הראשונה
const TTS_CACHE_DIR = path.join(DATA_DIR, 'tts-cache');
const ttsMemCache = new Map();          // מפתח -> data URI
const TTS_MEM_MAX = 120;
const TTS_MAX_CHARS = 1200;

// פינוי LRU במקום clear(). הגרסה הקודמת מחקה את *כל* המטמון ברגע שהתמלא -
// כלומר אחרי 120 הקראות, ההקראה הבאה של אפילו שאלה נפוצה חוזרת לסינתזה מלאה
// (כמה שניות) במקום להגיע מיידית. כאן נזרק רק הישן ביותר.
function rememberTts(key, uri) {
    if (ttsMemCache.has(key)) ttsMemCache.delete(key);
    ttsMemCache.set(key, uri);
    while (ttsMemCache.size > TTS_MEM_MAX) {
        ttsMemCache.delete(ttsMemCache.keys().next().value);
    }
}

// הרחבת קיצורים נפוצים לפני ההקראה (במקום לבקש זאת מהמודל בתוך הטקסט)
function speakText(t) {
    return String(t)
        .replace(/ס"מ/g, 'סנטימטר').replace(/מ"ר/g, 'מטר רבוע').replace(/מ"ק/g, 'מטר מעוקב')
        .replace(/ק"מ/g, 'קילומטר').replace(/ק"ג/g, 'קילוגרם').replace(/מ"ל/g, 'מיליליטר')
        .replace(/\s+/g, ' ').trim();
}

// v3: מבטל אודיו ישן במטמון (בזיכרון ובדיסק) שבו המודל הקריא את ההנחיות במקום את הטקסט
function ttsKey(text, voice) {
    return crypto.createHash('sha1').update('v3|' + voice + '|' + text).digest('hex');
}

// המודל מחזיר PCM גולמי (16 ביט, mono). דפדפן לא יודע לנגן PCM ערום,
// ולכן עוטפים בכותרת WAV — 44 בתים שהופכים אותו לקובץ תקין.
function pcmToWav(pcm, sampleRate = 24000, channels = 1, bits = 16) {
    const byteRate   = sampleRate * channels * bits / 8;
    const blockAlign = channels * bits / 8;
    const h = Buffer.alloc(44);
    h.write('RIFF', 0);
    h.writeUInt32LE(36 + pcm.length, 4);
    h.write('WAVE', 8);
    h.write('fmt ', 12);
    h.writeUInt32LE(16, 16);
    h.writeUInt16LE(1, 20);
    h.writeUInt16LE(channels, 22);
    h.writeUInt32LE(sampleRate, 24);
    h.writeUInt32LE(byteRate, 28);
    h.writeUInt16LE(blockAlign, 32);
    h.writeUInt16LE(bits, 34);
    h.write('data', 36);
    h.writeUInt32LE(pcm.length, 40);
    return Buffer.concat([h, pcm]);
}

// ניקוי סוף ההקראה: מודלי TTS מוסיפים לפעמים "גיצים"/נקישה קטועה אחרי המשפט האחרון.
// 1) מזהים הפסקה קצרה ואחריה פרץ קצר בסוף הקובץ וחותכים אותו.
// 2) מוסיפים fade-in קצר בהתחלה ו-fade-out בסוף כדי שלא תהיה נקישה בחיתוך.
function cleanPcm(pcm, rate) {
    const n = pcm.length >> 1;
    if (n < rate * 0.4) return pcm;
    const win = Math.max(1, Math.round(rate * 0.01));          // חלון 10ms
    const wins = Math.floor(n / win);
    const rms = new Float64Array(wins);
    let peak = 0;
    for (let w = 0; w < wins; w++) {
        let s = 0;
        for (let i = 0; i < win; i++) { const v = pcm.readInt16LE((w * win + i) * 2); s += v * v; }
        rms[w] = Math.sqrt(s / win);
        if (rms[w] > peak) peak = rms[w];
    }
    const quiet = Math.max(120, peak * 0.03);
    // מוצאים את סוף הדיבור הרגיל: הולכים אחורה על פרץ קצר (עד 150ms, קצר מכל מילה אמיתית) שלפניו שקט של 80ms+
    let end = wins;
    while (end > 0 && rms[end - 1] < quiet) end--;              // שקט בסוף הקובץ
    let burstEnd = end;                                          // סוף הפרץ האחרון
    let b = burstEnd;
    while (b > 0 && rms[b - 1] >= quiet) b--;                    // תחילת הפרץ האחרון
    const burstLen = burstEnd - b;
    let gap = 0, g = b;
    while (g > 0 && rms[g - 1] < quiet) { g--; gap++; }
    if (burstLen > 0 && burstLen <= 15 && gap >= 8 && g > 0) end = g;   // פרץ קצר אחרי הפסקה = רעש, חותכים
    const keepWins = Math.min(wins, end + 12);                   // משאירים 120ms שקט אחרי הדיבור
    const out = Buffer.from(pcm.subarray(0, keepWins * win * 2));
    const m = out.length >> 1;
    const fi = Math.min(m, Math.round(rate * 0.012)), fo = Math.min(m, Math.round(rate * 0.09));
    for (let i = 0; i < fi; i++) out.writeInt16LE(Math.round(out.readInt16LE(i * 2) * (i / fi)), i * 2);
    for (let i = 0; i < fo; i++) { const k = (m - 1 - i) * 2; out.writeInt16LE(Math.round(out.readInt16LE(k) * (i / fo)), k); }
    return out;
}
function cleanWavBuffer(buf) {
    try {
        if (buf.length < 100 || buf.toString('ascii', 0, 4) !== 'RIFF') return buf;
        const rate = buf.readUInt32LE(24);
        return pcmToWav(cleanPcm(buf.subarray(44), rate), rate);
    } catch (e) { return buf; }
}

function extractAudio(result) {
    const parts = result?.candidates?.[0]?.content?.parts || [];
    for (const p of parts) {
        if (p?.inlineData?.data) return p.inlineData;
    }
    return null;
}

async function synthesize(text, voice) {
    // חשוב: שולחים למודל רק את הטקסט להקראה, בלי שום הוראת סגנון/הגייה בתוכו.
    // מודלי TTS מקריאים בקול כל מילה שנשלחת אליהם, כולל הוראות ("הקרא בקול חם..."),
    // וזו הסיבה שהתלמידים שמעו את ההנחיות במקום את ההסבר. קיצורים מורחבים כאן בקוד.
    const prompt = speakText(text);

    let candidates;
    if (ttsModelInUse) candidates = [ttsModelInUse];
    else {
        const found = await discoverTtsModels();
        const all = Array.from(new Set([process.env.GEMINI_TTS_MODEL].concat(found, TTS_MODELS).filter(Boolean)));
        candidates = all.filter(m => !(ttsDeadUntil.get(m) > Date.now()));
        if (!candidates.length) candidates = all;
    }
    let lastErr = null;
    const attempts = [];

    for (const model of candidates) {
        try {
            // timeout לכל מודל בנפרד: בלי זה, מודל שנתקע גורם לכפתור "הקרא"
            // להיתקע לנצח במקום לעבור למודל הבא תוך שניות.
            const result = await withTimeout(genAI.models.generateContent({
                model,
                contents: [{ role: 'user', parts: [{ text: prompt }] }],
                config: {
                    responseModalities: ['AUDIO'],
                    speechConfig: {
                        languageCode: 'he-IL',
                        voiceConfig: { prebuiltVoiceConfig: { voiceName: voice } }
                    }
                }
            }), 12000, `tts:${model}`);
            const inline = extractAudio(result);
            if (!inline) throw new Error('no audio part in response');

            // קצב הדגימה מגיע לפעמים בתוך mimeType, למשל audio/L16;rate=24000
            const rateMatch = /rate=(\d+)/.exec(inline.mimeType || '');
            const rate = rateMatch ? parseInt(rateMatch[1], 10) : 24000;

            const pcm = Buffer.from(inline.data, 'base64');
            const wav = pcmToWav(cleanPcm(pcm, rate), rate);

            ttsModelInUse = model;
            console.log(`[speak] הצלחה עם המודל ${model} (${pcm.length} בתים, ${rate}Hz)`);
            return { wav, model, attempts };
        } catch (err) {
            lastErr = err;
            attempts.push({ model, error: err.message || String(err) });
            console.warn(`[speak] המודל ${model} נכשל: ${err.message}`);
            // אם המודל הנעול נכשל, נשחרר את הנעילה כדי לנסות אחרים בפעם הבאה
            if (ttsModelInUse === model) ttsModelInUse = null;
            if (/not.?found|404/i.test(err.message || '')) ttsDeadUntil.set(model, Date.now() + 30 * 60 * 1000);
        }
    }
    const e = lastErr || new Error('no TTS model available');
    e.attempts = attempts;
    throw e;
}

