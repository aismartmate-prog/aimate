// ═══ הגנת זמן-תגובה: אף קריאה לגוגל לא תתקע את המסך לנצח ═══
// בלי זה, אם ה-API של גוגל "נתקע" (קורה), הבקשה פשוט תלויה בלי סוף:
// התלמיד/הלקוח רואה מסך טעינה שלא נגמר. עם timeout - מקבלים שגיאה מהירה
// ומנסים שוב פעם אחת, שזה כמעט תמיד מצליח ולוקח פחות משנייה נוספת.
function withTimeout(promise, ms, label) {
    let t;
    const timeout = new Promise((_, reject) => {
        t = setTimeout(() => reject(new Error(`${label} timeout after ${ms}ms`)), ms);
    });
    return Promise.race([promise, timeout]).finally(() => clearTimeout(t));
}

async function withRetry(fn, { tries = 2, ms = 6000, label = 'gemini' } = {}) {
    let lastErr;
    for (let i = 1; i <= tries; i++) {
        try {
            return await withTimeout(fn(), ms, label);
        } catch (err) {
            lastErr = err;
            console.warn(`[${label}] ניסיון ${i}/${tries} נכשל: ${err.message}`);
        }
    }
    throw lastErr;
}

