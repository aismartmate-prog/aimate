//  חימום מקדים (pre-warm) - התיקון הכי משמעותי ל"פדיחה" בהדגמה
//  ---------------------------------------------------------------------------
//  בגרסה הקודמת, הלחיצה הראשונה על "הקרא שאלה" אחרי עליית השרת הייתה איטית
//  במיוחד: TTS_MODELS מנוסה אחד-אחד עד שאחד עובד. אם המודל הראשון ברשימה לא
//  זמין למפתח שלך, כל ניסיון כושל עולה סבב-הלוך-חזור מלא לגוגל - ורק אז עוברים
//  לבא. בהדגמה חיה זה נראה כאילו המערכת "נתקעה" בדיוק ברגע הכי גרוע.
//  כאן זה קורה פעם אחת בעלייה, בשקט: ttsModelInUse ננעל מראש, וחיבור ה-TLS
//  לגוגל כבר פתוח. הלחיצה הראשונה של הלקוח כבר מגיעה למסלול המהיר.
// ═══════════════════════════════════════════════════════════════════════════
async function prewarm() {
    if (!API_KEY) return;
    try {
        const t0 = Date.now();
        await synthesize('שלום', YONI_VOICE_NAME);
        console.log(`[prewarm] מודל TTS ננעל על ${ttsModelInUse} תוך ${Date.now() - t0}ms - הלחיצה הראשונה תהיה מהירה`);
    } catch (err) {
        console.warn('[prewarm] חימום TTS נכשל (לא קריטי):', err.message);
    }
}

