async function saveLessonProgress(studentId, entry) {
    if (!studentId) return;
    return enqueueDb(STUDENTS_DB_PATH, async () => {
        const db = await readStudentsDB();
        if (!db[studentId]) db[studentId] = { name: '', grade: '', gender: null, lessons: [] };
        const p = db[studentId];
        if (!Array.isArray(p.lessons)) p.lessons = [];

        if (entry.name) p.name = entry.name;
        if (entry.grade && gradeToNumber(entry.grade)) p.grade = entry.grade;
        if (cleanGender(entry.gender)) p.gender = cleanGender(entry.gender);
        // רמה וקצב הם מאפיינים של התלמיד/ה (לא של שיעור בודד) - מתעדכנים תמיד לערך האחרון
        if (cleanLevelPace(entry.level)) p.level = cleanLevelPace(entry.level);
        if (cleanLevelPace(entry.pace)) p.pace = cleanLevelPace(entry.pace);

        if (entry.subject || entry.summary || entry.strengths || entry.difficulties || entry.nextStep) {
            p.lessons.push({
                date: new Date().toISOString(),
                subject: entry.subject || '',
                summary: entry.summary || '',
                strengths: entry.strengths || '',
                difficulties: entry.difficulties || '',
                nextStep: entry.nextStep || ''
            });
            if (p.lessons.length > MAX_LESSONS_HISTORY) {
                p.lessons = p.lessons.slice(-MAX_LESSONS_HISTORY);
            }
        }
        await writeStudentsDB(db);
    });
}

async function saveChatHistory(studentId, transcript) {
    if (!studentId || !transcript) return;
    return enqueueDb(CHAT_HISTORY_DB_PATH, async () => {
        const db = await readChatHistoryDB();
        if (!db[studentId]) db[studentId] = [];
        let trimmed = String(transcript);
        if (trimmed.length > MAX_TRANSCRIPT_CHARS) {
            trimmed = trimmed.slice(0, 480) + '\n...\n' + trimmed.slice(-480);
        }
        db[studentId].push({ date: new Date().toISOString(), transcript: trimmed });
        if (db[studentId].length > MAX_CHAT_HISTORY) {
            db[studentId] = db[studentId].slice(-MAX_CHAT_HISTORY);
        }
        await writeChatHistoryDB(db);
    });
}

async function getLastChatTail(studentId) {
    if (!studentId) return '';
    try {
        const db = await readChatHistoryDB();
        const arr = db[studentId];
        if (!Array.isArray(arr) || !arr.length) return '';
        return String(arr[arr.length - 1].transcript || '').slice(-500);
    } catch (e) { return ''; }
}

