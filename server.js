// השדות (למשל: example הפך ממחרוזת למערך שורות). בלי זה, שיעורים ישנים
// שכבר נשמרו בדיסק לפי המבנה/העיצוב הקודם ימשיכו להיות מוגשים לנצח, גם
// אחרי שהקוד עודכן - בדיוק התופעה של "עדיין רואים את אותו עיצוב מבולגן".
const TOPIC_LESSON_VERSION = 'v3';

function topicLessonKey(subject, grade, topic, subtopic) {
    const raw = [TOPIC_LESSON_VERSION, subject, grade, topic, subtopic]
        .map(s => (s || '').toString().trim().toLowerCase())
        .join('|');
    return crypto.createHash('sha1').update(raw).digest('hex');
}

// מוציא בלוק JSON מתוך תשובת המודל גם אם הוא עטף אותו ב-```json...``` בטעות
function extractJsonBlock(text) {
    if (!text) return null;
    let t = text.trim();
    const fence = /```(?:json)?\s*([\s\S]*?)```/i.exec(t);
    if (fence) t = fence[1].trim();
    try { return JSON.parse(t); } catch (e) { /* ניפול לניסיון הבא */ }
    const first = t.indexOf('{');
    const last = t.lastIndexOf('}');
    if (first !== -1 && last !== -1 && last > first) {
        try { return JSON.parse(t.slice(first, last + 1)); } catch (e) { /* ויתור */ }
    }
    return null;
}

async function generateTopicLesson(subjectLabel, topicLabel, subtopicLabel) {
    const focus = subtopicLabel ? `${topicLabel} - ${subtopicLabel}` : topicLabel;
    const prompt =
        `אתה מורה פרטי מנוסה שבונה דף לימוד לתלמיד/ה על נושא לימודי - לא פותר תרגיל ` +
        `ספציפי. הנושא, במקצוע "${subjectLabel}", הוא: "${focus}". ` +
        `החזר אך ורק אובייקט JSON תקני יחיד (בלי טקסט נוסף, בלי markdown, בלי גדר קוד) ` +
        `במבנה המדויק הבא (כל הערכים בעברית תקנית וברורה, מתאימים לגיל התלמיד):\n` +
        `{\n` +
        `  "title": "שם קצר וברור לנושא",\n` +
        `  "definition": "2-3 משפטים קצרים המסבירים מהו העיקרון/ההגדרה המרכזית של הנושא, בשפה פשוטה",\n` +
        `  "steps": ["שלב 1 - איך ניגשים לפתור/להשתמש בזה בפועל", "שלב 2", "שלב 3 (אופציונלי, עד 4 שלבים בסה\\"כ)"],\n` +
        `  "example": ["שורה 1: משפט קצר על מה עושים + המשוואה שלו", "שורה 2: הצעד הבא + המשוואה שלו", "... (עד 6 שורות, כולל שורת תשובה סופית אחרונה)"],\n` +
        `  "commonMistake": "משפט אחד-שניים בלבד על טעות נפוצה שתלמידים עושים בנושא הזה, וכיצד להימנע ממנה",\n` +
        `  "narration": "טקסט רציף (לא רשימה, לא כותרות, בלי שום סימון מתמטי כמו $ או LaTeX - זה נקרא בקול) ` +
        `שמתמצת בעל-פה, בטון חם וסבלני של מורה שמסביר ליד הלוח, את ההגדרה, השיטה, דוגמה קצרה, והטעות הנפוצה - ` +
        `כ-60 עד 100 שניות דיבור (כ-150-260 מילים), מפורט ומלא ולא תמציתי מדי - חייב לכסות ` +
        `את ההגדרה, השיטה המלאה, דוגמה קונקרטית, והטעות הנפוצה. אל תפתח במילת ברכה ואל תסיים בשאלה."\n` +
        `}\n\n` +
        `כללי עיצוב מתמטי קריטיים - חלים על definition, steps, example, commonMistake (לא על narration):\n` +
        `1. כל ביטוי/משוואה/נוסחה מתמטית (כולל שברים, חזקות, משתנים, אחוזים עם משתנה) חייבת להיכתב ` +
        `בסימון LaTeX תקני, עטופה בסימני דולר בלבד - אף פעם לא בלעדיהם: "$x+3=7$" בתוך משפט, ` +
        `או "$$x+3=7$$" כשהיא כל השורה. לדוגמה: שבר כותבים "$\\frac{1}{2}$" ולא "1/2", חזקה כותבים ` +
        `"$x^2$" ולא "x^2", משתנה בודד כותבים "$x$" ולא "x". זה כלל ברזל - אין שום יוצא מן הכלל.\n` +
        `2. שדה "example" הוא מערך (array) של מחרוזות קצרות - לא מחרוזת אחת ולא פסקה. כל איבר במערך ` +
        `הוא שורה עצמאית אחת: משפט הסבר קצר (עד 8 מילים) ולידו/אחריו המשוואה שלו בסימון $ מתאים. ` +
        `אסור לרכז כמה שלבי חישוב באיבר אחד. האיבר האחרון חייב להיות שורת התשובה הסופית בלבד, ` +
        `בסגנון: "תשובה: ..." עם התוצאה הסופית ב-$...$.`;

    const result = await withRetry(() => genAI.models.generateContent({
        model: TOPIC_LESSON_TEXT_MODEL,
        contents: [{ role: 'user', parts: [{ text: prompt }] }],
        config: { responseMimeType: 'application/json' }
    }), { tries: 2, ms: 16000, label: 'topic-lesson-json' });

    const rawText = (result?.candidates?.[0]?.content?.parts || [])
        .map(p => p?.text || '')
        .join(' ')
        .trim();
    const parsed = extractJsonBlock(rawText);
    if (!parsed || !parsed.narration) throw new Error('לא התקבל שיעור תקין (JSON) מהמודל');

    // ניקוי/הגנה בסיסית - שדות חסרים לא יפילו את כל הבקשה. "example" תומך גם
    // בפורמט ישן (מחרוזת בודדת, מהגרסה הקודמת) למקרה שהמודל בכל זאת מחזיר כך -
    // מפרקים אותו לפי שורות כדי שהתצוגה עדיין תצא נקייה.
    let exampleLines;
    if (Array.isArray(parsed.example)) {
        exampleLines = parsed.example.map(s => (s || '').toString().slice(0, 300)).filter(Boolean).slice(0, 8);
    } else {
        exampleLines = (parsed.example || '').toString().split('\n').map(s => s.trim()).filter(Boolean).slice(0, 8);
    }

    return {
        title: (parsed.title || topicLabel || '').toString().slice(0, 200),
        definition: (parsed.definition || '').toString().slice(0, 800),
        steps: Array.isArray(parsed.steps) ? parsed.steps.map(s => (s || '').toString().slice(0, 400)).filter(Boolean).slice(0, 6) : [],
        example: exampleLines,
        commonMistake: (parsed.commonMistake || '').toString().slice(0, 500),
        narration: (parsed.narration || '').toString().slice(0, TTS_MAX_CHARS)
    };
}

app.post('/live-tutor/api/topic-lesson', async (req, res) => {
    if (!API_KEY) return res.status(500).json({ error: 'GEMINI_API_KEY missing' });
    try {
        const body = req.body || {};
        const subject = (body.subject || '').toString().slice(0, 60);
        const grade = (body.grade || '').toString().slice(0, 30);
        const topic = (body.topic || '').toString().slice(0, 200);
        const subtopic = (body.subtopic || '').toString().slice(0, 200);
        // תוויות תצוגה (עברית, לשימוש כתוכן ההסבר) - אם לא סופקו, נופלים חזרה למזהים הגולמיים
        const subjectLabel = (body.subjectLabel || subject || '').toString().slice(0, 100);
        const topicLabel = (body.topicLabel || topic || '').toString().slice(0, 200);
        const subtopicLabel = (body.subtopicLabel || '').toString().slice(0, 200);

        if (!topic) return res.status(400).json({ error: 'Missing topic' });

        const key = topicLessonKey(subject, grade, topic, subtopic);

        // 1. מטמון בזיכרון - מיידי
        if (topicLessonMemCache.has(key)) {
            return res.json({ lesson: topicLessonMemCache.get(key), cached: 'memory' });
        }

        // 2. מטמון בדיסק - שורד הפעלה מחדש של השרת
        const jsonPath = path.join(TOPIC_LESSON_DIR, key + '.json');
        try {
            const savedJson = await fs.promises.readFile(jsonPath, 'utf8');
            const lesson = JSON.parse(savedJson);
            topicLessonMemCache.set(key, lesson);
            return res.json({ lesson, cached: 'disk' });
        } catch (e) { /* עוד לא נוצר לצירוף הזה - ממשיכים ליצירה חד-פעמית */ }

        // 3. יצירה חדשה - קורה פעם אחת בלבד לכל נושא+תת-נושא (לא פר-תלמיד), ואז
        // נשמרת לתמיד בדיסק. כל התלמידים הבאים שיבקשו יקבלו אותו שיעור בדיוק, מיידית.
        // חשוב: כאן רק הטקסט/JSON נוצר - בלי סינתזת קול - כדי שהתוכן החזותי יעלה
        // לתלמיד מהר ככל האפשר. הקול מובא בנפרד ע"י הלקוח דרך /live-tutor/api/speak
        // (שכבר יודע לבצע סינתזה+מטמון בעצמו), כדי לא לחסום את התצוגה הראשונית.
        const lesson = await generateTopicLesson(subjectLabel, topicLabel, subtopicLabel);
        topicLessonMemCache.set(key, lesson);

        fs.promises.mkdir(TOPIC_LESSON_DIR, { recursive: true })
            .then(() => fs.promises.writeFile(jsonPath, JSON.stringify(lesson), 'utf8'))
            .catch(() => { /* מטמון דיסק הוא בונוס - אם נכשל, ניצור שוב בפעם הבאה */ });

        res.json({ lesson, cached: false });
    } catch (err) {
        console.error('[topic-lesson] שגיאה:', err);
        res.status(500).json({ error: err.message || String(err) });
    }
});

// ═══════════════════════════════════════════════════════════════════════════
//  "לוח" - הופך את מה שהמורה אמר בקול לביטויים מתמטיים כתובים (LaTeX)
//  ---------------------------------------------------------------------------
//  הקול של המורה מקריא "מינוס ארבע איקס שווה ארבעים", והתמלול נשאר מילולי
//  וקשה לקריאה. אחרי סוף כל תור של המורה, הלקוח שולח לכאן את הטקסט וקורא
//  לכאן *בנפרד* מהשיחה החיה (לא חוסם ולא מאט את הקול), ומקבל חזרה שורות
//  מסודרות להצגה על לוח. נשמר במטמון לפי טקסט.
// ═══════════════════════════════════════════════════════════════════════════
const BOARD_MODEL = process.env.GEMINI_BOARD_MODEL || 'gemini-2.5-flash-lite';
const boardCache = new Map();
const BOARD_CACHE_MAX = 300;
const BOARD_TRIGGER = /[0-9=+×÷]|שווה|פלוס|מינוס|פחות|ועוד|כפול|חלקי|איקס|אקס|וואי|בריבוע|שורש|שבר/;

app.post('/live-tutor/api/board', async (req, res) => {
    try {
        const text = String((req.body && req.body.text) || '').replace(/\s+/g, ' ').trim().slice(0, 1500);
        if (!API_KEY || text.length < 5 || !BOARD_TRIGGER.test(text)) return res.json({ lines: [] });

        const key = crypto.createHash('sha1').update(text).digest('hex');
        if (boardCache.has(key)) return res.json({ lines: boardCache.get(key), cached: true });

        const prompt =
            'להלן תמלול של מורה פרטי שמדבר בקול עם תלמיד. הוצא ממנו את הביטויים, המשוואות ושלבי החישוב המתמטיים ' +
            'שהמורה אמר בפועל (גם אם נאמרו במילים בעברית, כמו "מינוס ארבע איקס שווה ארבעים"), לפי הסדר שבו נאמרו. ' +
            'כל שורה היא ביטוי או משוואה אחת בסימון LaTeX נקי, בלי סימני דולר ובלי טקסט עברי. ' +
            'חוקים: רק מה שנאמר בפועל - אל תפתור, אל תתקן, אל תוסיף שלבים. שבר: \\frac{a}{b}. חזקה: x^{2}. כפל: \\cdot או \\times. ' +
            'חילוק: \\div. שורש: \\sqrt{}. מינוס ארבע איקס = -4x. אם אין בתמלול ביטוי מתמטי - החזר רשימה ריקה. עד 8 שורות. ' +
            'החזר אך ורק JSON במבנה {"lines":["..."]}.\n\nתמלול:\n' + text;

        const result = await withRetry(() => genAI.models.generateContent({
            model: BOARD_MODEL,
            contents: [{ role: 'user', parts: [{ text: prompt }] }],
            config: { responseMimeType: 'application/json', temperature: 0 }
        }), { tries: 1, ms: 7000, label: 'board' });

        const raw = (result?.candidates?.[0]?.content?.parts || []).map(p => p?.text || '').join('').trim();
        const parsed = extractJsonBlock(raw);
        let lines = (parsed && Array.isArray(parsed.lines) ? parsed.lines : [])
            .map(l => String(l || '').replace(/\$/g, '').trim())
            .filter(l => l && l.length <= 160 && !/[\u0590-\u05FF]/.test(l))
            .slice(0, 8);

        boardCache.set(key, lines);
        while (boardCache.size > BOARD_CACHE_MAX) boardCache.delete(boardCache.keys().next().value);
        res.json({ lines });
    } catch (err) {
        console.warn('[board] נכשל (לא קריטי):', err.message);
        res.json({ lines: [] });
    }
});

